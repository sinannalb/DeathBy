export function mergeIstanbulDistricts(
  extraItems: Array<{ district: string; neighborhood: string }>,
): IstanbulDistrictEntry[] {
  const map = new Map<string, Set<string>>();

  for (const entry of ISTANBUL_DISTRICTS) {
    map.set(entry.district, new Set(entry.neighborhoods));
  }

  for (const item of extraItems) {
    const d = item.district.trim();
    const n = item.neighborhood.trim();
    if (!d || !n) continue;
    const set = map.get(d) ?? new Set<string>();
    set.add(n);
    map.set(d, set);
  }

  return Array.from(map.entries())
    .sort(([a], [b]) => a.localeCompare(b, "tr"))
    .map(([district, set]) => ({
      district,
      neighborhoods: Array.from(set).sort((a, b) => a.localeCompare(b, "tr")),
    }));
}
